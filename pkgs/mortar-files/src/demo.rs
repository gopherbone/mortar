/// What the emulator would say.
pub fn play_config(root: &Path) -> PlayConfig {
    let json = serde_json::json!({
        "romDirs": [root.join("play/roms")],
        "systems": [
            {"id":"gb","folders":["gb"],"extensions":["gb"]},
            {"id":"gbc","folders":["gbc"],"extensions":["gbc"]},
            {"id":"gba","folders":["gba"],"extensions":["gba"]},
            {"id":"nes","folders":["nes"],"extensions":["nes"]},
            {"id":"snes","folders":["snes"],"extensions":["sfc","smc"]},
        ]
    });
    PlayConfig::parse(&json.to_string(), root).unwrap_or_default()
}

/// A guard for the demo: everything in it, with a made-up read-only folder.
pub fn guard(env: &PlaceEnv) -> Guard {
    let mut read_only: Vec<PathBuf> = ops::READ_ONLY.iter().map(PathBuf::from).collect();
    read_only.push(env.root.join("nix"));
    Guard { read_only, pinned: vec![env.home.join("Games"), env.play.join("roms"), env.play.join("saves"), env.play.join("bios"), env.trash.clone()], home: Some(env.home.clone()) }
}

pub fn clock() -> Clock {
    Clock { fixed_now: Some(NOW) }
}
