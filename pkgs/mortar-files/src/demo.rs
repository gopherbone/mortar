/// The demo's "now": a Monday morning, UTC.
pub const NOW: i64 = 1_793_620_800;
const DAY: i64 = 86_400;

fn touch(p: &Path, age: i64) {
    let t = UNIX_EPOCH + Duration::from_secs((NOW - age) as u64);
    if let Ok(f) = fs::File::options().write(true).open(p) {
        let _ = f.set_modified(t);
    } else if let Ok(f) = fs::File::open(p) {
        let _ = f.set_modified(t);
    }
}

/// A file of `size` bytes: a head of generated bytes, then a hole.
fn file(p: &Path, size: u64, age: i64, style: u8) {
    let mut r = Rng::seed(p.file_name().unwrap_or_default().as_encoded_bytes());
    let n = size.min(512) as usize;
    let mut head: Vec<u8> = (0..n)
        .map(|i| {
            let v = r.next();
            match style {
                // cartridge: a logo block, zeros, then code
                0 => {
                    if i < 4 { 0xc3 } else if i < 20 { 0 } else if i < 48 { (v >> 8) as u8 | 0xc0 } else if i < 64 { 0x20 + (v % 90) as u8 } else { (v >> 16) as u8 }
                }
                // compressed: noise
                1 => (v >> 8) as u8,
                // a save: mostly empty
                _ => {
                    if v % 7 == 0 { (v >> 8) as u8 } else { 0 }
                }
            }
        })
        .collect();
    if style == 1 && head.len() > 4 {
        head[..4].copy_from_slice(b"PK\x03\x04");
    }
    fs::write(p, &head).unwrap();
    let f = fs::File::options().write(true).open(p).unwrap();
    f.set_len(size).unwrap();
    drop(f);
    touch(p, age);
}

fn text(p: &Path, body: &str, age: i64) {
    fs::write(p, body).unwrap();
    touch(p, age);
}

/// A generated picture: bands of tiles over a sky.
fn picture(p: &Path, w: u32, h: u32, sky: [u8; 3], land: [u8; 3], sun: [u8; 3], age: i64) {
    use resvg::tiny_skia::{Color, Paint, Pixmap, Rect, Transform};
    let mut pm = Pixmap::new(w, h).unwrap();
    pm.fill(Color::from_rgba8(sky[0], sky[1], sky[2], 255));
    let mut paint = Paint::default();
    paint.set_color_rgba8(sun[0], sun[1], sun[2], 255);
    let (cx, cy, rad) = (w as f32 * 0.68, h as f32 * 0.38, h as f32 * 0.18);
    let cell = (w / 40).max(4) as f32;
    let mut y = 0.0;
    let mut r = Rng::seed(p.as_os_str().as_encoded_bytes());
    while y < h as f32 {
        let mut x = 0.0;
        while x < w as f32 {
            let d = ((x - cx).powi(2) + (y - cy).powi(2)).sqrt();
            let horizon = h as f32 * (0.62 + 0.08 * ((x / w as f32 * 7.0).sin()));
            if y > horizon {
                let v = (r.next() % 30) as u8;
                paint.set_color_rgba8(land[0].saturating_sub(v), land[1].saturating_sub(v), land[2].saturating_sub(v), 255);
                pm.fill_rect(Rect::from_xywh(x, y, cell, cell).unwrap(), &paint, Transform::identity(), None);
            } else if d < rad {
                paint.set_color_rgba8(sun[0], sun[1], sun[2], 255);
                pm.fill_rect(Rect::from_xywh(x, y, cell, cell).unwrap(), &paint, Transform::identity(), None);
            }
            x += cell;
        }
        y += cell;
    }
    pm.save_png(p).unwrap();
    touch(p, age);
}

const MB: u64 = 1024 * 1024;

/// Build the tree. Returns the place inputs.
pub fn build(root: &Path) -> PlaceEnv {
    let home = root.join("home");
    let play = root.join("play");
    for d in ["Documents", "Downloads", "Music/Songs", "Pictures/Screenshots", ".config/app", "Empty folder", "Games"] {
        fs::create_dir_all(home.join(d)).unwrap();
    }
    for d in ["roms/gb", "roms/gbc", "roms/gba", "roms/nes", "roms/snes", "saves/gba", "saves/gbc", "bios"] {
        fs::create_dir_all(play.join(d)).unwrap();
    }

    // Home
    text(&home.join("Documents/notes.txt"), NOTES, 2 * 3600);
    text(&home.join("Documents/packing list.md"), "- charger\n- the good earphones\n- spare card\n- snacks\n", 5 * DAY);
    text(&home.join("Documents/high scores.csv"), "game,score\nMoon Miner,48210\nStar Courier,9920\nPocket King,7\n", 12 * DAY);
    file(&home.join("Documents/old manual.pdf"), 4 * MB, 300 * DAY, 1);
    text(&home.join("today.txt"), "Back up the saves.\nMove the screenshots off.\nFind the other cable.\n", 40 * 60);
    file(&home.join("Downloads/homebrew-pack.zip"), 820 * MB, 3 * DAY, 1);
    file(&home.join("Downloads/soundfont.7z"), 410 * MB, 9 * DAY, 1);
    file(&home.join("Downloads/level editor.tar.gz"), 12 * MB, 21 * DAY, 1);
    file(&home.join("Music/Songs/night drive.m8s"), 96 * 1024, 2 * DAY, 2);
    file(&home.join("Music/Songs/harbour lights.m8s"), 128 * 1024, 6 * DAY, 2);
    file(&home.join("Music/Songs/slow tide.flac"), 340 * MB, 30 * DAY, 1);
    file(&home.join("Music/mixdown.wav"), 580 * MB, 8 * DAY, 1);
    picture(&home.join("Pictures/Harbour at dusk.png"), 640, 480, [255, 159, 103], [60, 50, 110], [255, 211, 48], 4 * DAY);
    picture(&home.join("Pictures/Lime hills.png"), 640, 480, [225, 235, 247], [120, 170, 40], [255, 119, 168], 11 * DAY);
    picture(&home.join("Pictures/Moon over water.png"), 480, 640, [40, 40, 90], [20, 60, 120], [225, 235, 247], 25 * DAY);
    fs::write(home.join("Pictures/Red square.jpg"), include_bytes!("../tests/sample.jpg")).unwrap();
    touch(&home.join("Pictures/Red square.jpg"), 60 * DAY);
    for (i, (a, b)) in [([20u8, 20, 40], [80u8, 180, 90]), ([120, 180, 255], [70, 150, 60]), ([20, 20, 30], [200, 60, 90])].iter().enumerate() {
        picture(&home.join(format!("Pictures/Screenshots/shot {:02}.png", i + 1)), 320, 240, *a, *b, [255, 211, 48], (i as i64 + 1) * DAY);
    }
    text(&home.join(".profile"), "export EDITOR=vi\n", 200 * DAY);
    text(&home.join(".config/app/settings.toml"), "theme = \"pond\"\nsound = true\n", 90 * DAY);
    std::os::unix::fs::symlink("../../play/roms", home.join("Games/roms")).unwrap();
    std::os::unix::fs::symlink("nowhere-any-more", home.join("Games/old link")).unwrap();

    // Games: made-up titles
    let roms = play.join("roms");
    for (i, n) in ["Pocket King (USA)", "Pocket King DX (USA, Europe)", "Moss Garden", "Tiny Lighthouse", "Beetle Rally"].iter().enumerate() {
        file(&roms.join(format!("gbc/{n}.gbc")), (i as u64 + 1) * 40 * MB, (i as i64 + 2) * DAY, 0);
    }
    for (i, n) in ["Star Courier (USA)", "Moon Miner", "Cave Runner II", "Paper Wings", "Hexagon Harvest", "Ten Thousand Steps", "Quiet Station", "Lantern Road", "Salt Flats Racing", "Night Ferry", "The Long Way Round (Europe) (Rev 1) (Translated) (Extended Edition)"].iter().enumerate() {
        file(&roms.join(format!("nes/{n}.nes")), (128 + i as u64 * 96) * 1024, (i as i64 + 1) * 3 * DAY, 0);
    }
    for (i, n) in ["Crystal Orchard", "Ember Knights", "Glass Tower"].iter().enumerate() {
        file(&roms.join(format!("gba/{n}.gba")), (180 + i as u64 * 160) * MB, (i as i64 + 4) * DAY, 0);
    }
    for (i, n) in ["Ring Valley", "Sky Forge"].iter().enumerate() {
        file(&roms.join(format!("snes/{n}.sfc")), (120 + i as u64 * 90) * MB, (i as i64 + 40) * DAY, 0);
    }
    file(&roms.join("gb/Burrow.gb"), 256 * 1024, 70 * DAY, 0);

    // Saves and BIOS
    file(&play.join("saves/gba/Crystal Orchard.sav"), 128 * 1024, 3 * 3600, 2);
    file(&play.join("saves/gba/Ember Knights.sav"), 64 * 1024, 5 * DAY, 2);
    file(&play.join("saves/gbc/Moss Garden.srm"), 32 * 1024, DAY, 2);
    file(&play.join("bios/sample-bios.bin"), 16 * 1024, 400 * DAY, 1);
    text(&play.join("bios/where these come from.txt"), "BIOS files are yours to provide. None ship with Mortar.\n", 400 * DAY);

    // A stand-in for the system's read-only tree.
    for d in ["nix/store/abc123-mortar-shell/bin", "nix/store/def456-fonts", "nix/var/profiles"] {
        fs::create_dir_all(root.join(d)).unwrap();
    }
    file(&root.join("nix/store/abc123-mortar-shell/bin/mortar-shell"), 9 * MB, 30 * DAY, 1);
    text(&root.join("nix/README"), "Everything in here is managed by Nix.\n", 30 * DAY);

    // folders' times, last: writing into them moved these
    fn age_dirs(d: &Path, r: &mut Rng) {
        for e in fs::read_dir(d).unwrap().flatten() {
            if e.file_type().unwrap().is_dir() {
                age_dirs(&e.path(), r);
                touch(&e.path(), (r.next() % 30 + 1) as i64 * DAY);
            }
        }
    }
    age_dirs(root, &mut Rng::seed(b"ages"));

    let trash = home.join(".local/share/Trash");
    PlaceEnv { home, play, mountinfo: root.join("no-mountinfo"), root: root.to_path_buf(), trash }
}

